#!/usr/bin/env python3
"""Rebuild historical U-Boot source and compare with the measured live SD bytes."""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("f1sdk", str(HERE / "sdk.py"))
sdk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sdk)
COMMITS = {
    "c5335a4": "c5335a470bf15ef345bc8db886c3f58b10bdf85d",
    "af73846": "af73846627a4431472b4dfb4cd22b96c6b7c09be",
}
EXPECTED = "71e34730de102099163f014c528ca0656bb1ef5c81fc2756f6a32477cd3cac04"
TIMESTAMP = [
    '#define U_BOOT_DATE "Aug 22 2026"',
    '#define U_BOOT_TIME "10:08:59"',
    '#define U_BOOT_TZ "-0700"',
    '#define U_BOOT_DMI_DATE "08/22/2026"',
    '#define U_BOOT_BUILD_DATE 0x20260822',
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", choices=sorted(COMMITS), default="c5335a4")
    parser.add_argument("-j", type=int, default=2)
    args = parser.parse_args()
    if args.j < 1 or args.j > 8:
        parser.error("jobs must be between1 and8")
    with sdk.locked():
        original, _ = sdk.validate_source("uboot")
        commit = COMMITS[args.source]
        sdk.capture(["git", "cat-file", "-e", commit + "^{commit}"], original)
        sdk.check_output(create=True)
        target = sdk.OUT / "provenance" / ("uboot-" + args.source)
        if target.is_symlink() or not sdk.contained(target, sdk.OUT):
            raise RuntimeError("Unsafe provenance build path")
        stamp = target / ".sdk-source-commit"
        if target.exists():
            if stamp.is_symlink() or not stamp.is_file() or stamp.read_text().strip() != commit:
                raise RuntimeError("Unrecognized existing provenance source directory")
        else:
            target.mkdir(parents=True)
            with tempfile.TemporaryFile() as archive:
                subprocess.run(["git", "archive", commit], cwd=str(original), stdout=archive, check=True)
                archive.seek(0)
                sdk.extract_archive(archive, target)
            shutil.copy2(str(sdk.ROOT / "sdk-support/configs/uboot.config"), str(target / ".config"))
            stamp.write_text(commit + "\n")
        env = os.environ.copy()
        env["PATH"] = str(sdk.compiler_bin()) + os.pathsep + env.get("PATH", "")
        env["LC_ALL"] = "C"
        timestamp = "filechk_timestamp.h=printf '%s\\n' " + " ".join(shlex.quote(line) for line in TIMESTAMP)
        make = ["make", "ARCH=arm", "CROSS_COMPILE=arm-linux-gnueabi-",
                "LOCALVERSION=-00008-gaf73846-dirty", timestamp]
        sdk.run(make + ["olddefconfig"], target, env)
        sdk.run(make + ["-j{}".format(args.j)], target, env)
        artifact = target / "u-boot-sunxi-with-spl.bin"
        report = {"source_commit": commit, "config_sha256": sdk.digest(target / ".config"),
                  "timestamp_header": (target / "include/generated/timestamp_autogenerated.h").read_text(),
                  "version_header": (target / "include/generated/version_autogenerated.h").read_text(),
                  "sha256": sdk.digest(artifact), "bytes": artifact.stat().st_size,
                  "live_sd_sha256": EXPECTED, "live_sd_offset": 8192,
                  "board_deployed": False}
        report["binary_identical_to_live_sd"] = report["sha256"] == EXPECTED and report["bytes"] == 548864
        (target / "provenance.json").write_text(json.dumps(report, indent=2) + "\n")
        print(json.dumps(report, indent=2))
        return 0 if report["binary_identical_to_live_sd"] else 2


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print("Historical U-Boot verification failed: {}".format(error), file=sys.stderr)
        sys.exit(1)
